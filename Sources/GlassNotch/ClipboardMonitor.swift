import AppKit

/// Recent clipboard history, kept in memory only (never written to disk).
///
/// Items that password managers mark as concealed or transient are skipped.
@MainActor
final class ClipboardMonitor: ObservableObject {
    struct Item: Identifiable {
        enum Content {
            case text(String)
            case image(NSImage)
            case files([URL])
        }

        let id = UUID()
        let content: Content
        let date = Date()
    }

    @Published private(set) var items: [Item] = []

    private var changeCount = NSPasteboard.general.changeCount
    private var timer: Timer?
    private let maxItems = 20
    private let maxImages = 6

    /// Pasteboard markers (nspasteboard.org) for content that should not be recorded.
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
    ]

    func start() {
        if ProcessInfo.processInfo.environment["GLASSNOTCH_SAMPLE_CLIPS"] != nil {
            // Debug aid: sample history, without touching the real clipboard.
            for text in ["git commit -m \"Liquid glass notch\"", "https://developer.apple.com/documentation/appkit",
                         "Meeting moved to 4:30, same room", "let glass = NSGlassEffectView()"] {
                add(.text(text))
            }
            add(.files([URL(fileURLWithPath: "/Applications/GlassNotch.app")]))
        }
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func check() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount

        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }

        if let urls = pasteboard.readObjects(forClasses: [NSURL.self],
                                             options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            add(.files(urls))
        } else if let text = pasteboard.string(forType: .string),
                  !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            add(.text(text))
        } else if let image = NSImage(pasteboard: pasteboard) {
            add(.image(image))
        }
    }

    private func add(_ content: Content) {
        removeDuplicates(of: content)
        items.insert(Item(content: content), at: 0)
        // Bound memory: few images, limited history.
        var images = 0
        items.removeAll { item in
            guard case .image = item.content else { return false }
            images += 1
            return images > maxImages
        }
        if items.count > maxItems { items.removeLast(items.count - maxItems) }
    }

    private typealias Content = Item.Content

    private func removeDuplicates(of content: Content) {
        items.removeAll { item in
            switch (item.content, content) {
            case let (.text(a), .text(b)): a == b
            case let (.files(a), .files(b)): a == b
            default: false
            }
        }
    }

    /// Puts an item back on the clipboard and moves it to the front.
    func copy(_ item: Item) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch item.content {
        case .text(let text): pasteboard.setString(text, forType: .string)
        case .image(let image): pasteboard.writeObjects([image])
        case .files(let urls): pasteboard.writeObjects(urls as [NSURL])
        }
        changeCount = pasteboard.changeCount
        if let index = items.firstIndex(where: { $0.id == item.id }), index > 0 {
            items.insert(items.remove(at: index), at: 0)
        }
    }

    func remove(_ item: Item) {
        items.removeAll { $0.id == item.id }
    }

    func clear() {
        items.removeAll()
    }
}
